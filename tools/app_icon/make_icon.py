#!/usr/bin/env python3
"""Draws the icon for the Strava API application (docs/app_icon.png) and embeds it in the
firmware (lib/SetupPortal/src/AppIcon.h), so the setup page offers it for download.

An e-paper device with a bar chart and a route on its screen, on a transparent background. Needs Pillow:
    python3 tools/app_icon/make_icon.py
"""

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
PNG_PATH = ROOT / "docs" / "app_icon.png"
HEADER_PATH = ROOT / "lib" / "SetupPortal" / "src" / "AppIcon.h"

SIZE = 512
SCALE = 4  # drawn larger and scaled down, for smooth edges
COLORS = 32  # the flat drawing needs few colors, which keeps the PNG small

CLEAR = (0, 0, 0, 0)
BEZEL = (38, 38, 38, 255)
PAPER = (238, 236, 228, 255)
PURPLE = (124, 58, 237, 255)
GREY = (150, 150, 146, 255)


def catmull_rom(points, steps=24):
    """Smooth curve through points"""
    pts = [points[0]] + points + [points[-1]]
    curve = []
    for i in range(1, len(pts) - 2):
        p0, p1, p2, p3 = pts[i - 1], pts[i], pts[i + 1], pts[i + 2]
        for s in range(steps):
            t = s / steps
            curve.append(tuple(
                0.5 * (2 * p1[k] + (-p0[k] + p2[k]) * t
                       + (2 * p0[k] - 5 * p1[k] + 4 * p2[k] - p3[k]) * t * t
                       + (-p0[k] + 3 * p1[k] - 3 * p2[k] + p3[k]) * t * t * t)
                for k in range(2)))
    curve.append(points[-1])
    return curve


def draw_icon():
    s = SIZE * SCALE
    u = s / 512  # coordinates below are on a 512 grid
    img = Image.new("RGBA", (s, s), CLEAR)
    d = ImageDraw.Draw(img)

    def box(x0, y0, x1, y1):
        return [x0 * u, y0 * u, x1 * u, y1 * u]

    def dot(x, y, r, fill, outline=None, width=0):
        d.ellipse(box(x - r, y - r, x + r, y + r), fill=fill, outline=outline, width=int(width * u))

    # the device, in landscape like the display
    d.rounded_rectangle(box(56, 112, 456, 400), radius=34 * u, fill=BEZEL)
    d.rounded_rectangle(box(80, 136, 432, 376), radius=10 * u, fill=PAPER)

    # bar chart on the left part of the screen, on a grey baseline
    for x, top in ((112, 270), (146, 214), (180, 296), (214, 182)):
        d.rounded_rectangle(box(x, top, x + 24, 336), radius=5 * u, fill=PURPLE)
    d.rounded_rectangle(box(104, 336, 246, 344), radius=4 * u, fill=GREY)

    # route on the right part
    route = catmull_rom([(274, 330), (300, 308), (304, 262), (342, 248), (350, 202),
                         (386, 178), (406, 208), (382, 244), (404, 290), (368, 326)], steps=80)
    # dots along the curve instead of a line: a polyline this dense gets gaps at its joints
    for x, y in route:
        dot(x, y, 7.5, PURPLE)
    dot(274, 330, 14, PAPER, PURPLE, 9)  # start
    dot(368, 326, 14, PURPLE)  # finish

    img = img.resize((SIZE, SIZE), Image.LANCZOS)
    return img.quantize(COLORS, method=Image.Quantize.FASTOCTREE)  # keeps the transparency


def write_header(png: bytes):
    lines = [", ".join(f"0x{b:02x}" for b in png[i:i + 16]) for i in range(0, len(png), 16)]
    body = ",\n    ".join(lines)
    HEADER_PATH.write_text(
        "// Generated by tools/app_icon/make_icon.py from docs/app_icon.png, don't edit\n"
        "#ifndef APP_ICON_H\n#define APP_ICON_H\n\n#include <Arduino.h>\n\n"
        "// Icon for the Strava API application, offered for download on the setup page\n"
        f"static const uint8_t APP_ICON_PNG[] PROGMEM = {{\n    {body}\n}};\n\n"
        "#endif  // APP_ICON_H\n")


def main():
    draw_icon().save(PNG_PATH, optimize=True)
    png = PNG_PATH.read_bytes()
    write_header(png)
    print(f"{PNG_PATH.relative_to(ROOT)}: {len(png)} bytes")


if __name__ == "__main__":
    main()
